import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readConfig } from '../src/config';
import { type ExtractResult, extractNotice } from '../src/extract';
import { compareToSpecimen, type FieldResult, groupPath } from '../src/map/compare';
import { sha256 } from '../src/providers/fixture';
import type { Notice } from '../src/schema/notice';

/**
 * Runs the acceptance inputs and compares each extraction with its ground truth, field by field.
 * `--mode live` calls the model (and, with EXTRACT_MODE=record, records fixtures); `--mode fixture` replays them offline.
 */

const REPO_ROOT = fileURLToPath(new URL('../../..', import.meta.url));
const SPECIMENS = join(REPO_ROOT, 'fixtures/specimens');
export const RESULTS_DIR = fileURLToPath(new URL('./results', import.meta.url));

export const ACCEPTANCE_INPUTS = [
  { file: 'specimen-1-form28.pdf', specimenId: 'specimen-1-form28' },
  { file: 'specimen-2-form29.pdf', specimenId: 'specimen-2-form29' },
  { file: 'specimen-3-courier.pdf', specimenId: 'specimen-3-courier' },
  { file: 'specimen-2-form29.png', specimenId: 'specimen-2-form29' },
  { file: 'specimen-2-form29.photo.jpg', specimenId: 'specimen-2-form29' },
] as const;

export type EvalInput = { file: string; specimenId: string; bytes: Uint8Array; truth: unknown };

export type Rate = { matched: number; total: number; rate: number };

export type InputResult = {
  file: string;
  specimenId: string;
  sha256: string;
  ok: boolean;
  reason?: string;
  schemaValid: boolean;
  kind?: string;
  matched: number;
  total: number;
  rate: number;
  needsConfirmation: number;
  wrong: Omit<FieldResult, 'match'>[];
};

export type EvalResult = {
  generatedAt: string;
  model: string;
  threshold: number;
  inputs: InputResult[];
  overall: Rate;
  perField: Record<string, Rate>;
  flaggedWrong: { flagged: number; wrong: number; rate: number };
};

/** A share as a percentage with one decimal, for reporting only. */
const pct = (n: number, d: number) => (d === 0 ? 0 : Number(((n / d) * 100).toFixed(1)));

export async function runEval(opts: {
  inputs: EvalInput[];
  extract: (i: EvalInput) => Promise<ExtractResult>;
  model: string;
  threshold?: number;
  now?: () => Date;
}): Promise<EvalResult> {
  const inputs: InputResult[] = [];
  const all: FieldResult[] = [];
  for (const input of opts.inputs) {
    const r = await opts.extract(input);
    // A failed extraction is compared as an empty one: every truth field counts as wrong.
    const fields = compareToSpecimen(r.ok ? r.notice : ({} as Notice), input.truth);
    all.push(...fields);
    const matched = fields.filter((f) => f.match).length;
    inputs.push({
      file: input.file,
      specimenId: input.specimenId,
      sha256: sha256(input.bytes),
      ok: r.ok,
      ...(r.ok ? {} : { reason: r.reason }),
      schemaValid: r.ok,
      ...(r.ok ? { kind: r.notice.kind } : {}),
      matched,
      total: fields.length,
      rate: pct(matched, fields.length),
      needsConfirmation: r.ok ? r.needsConfirmation.length : 0,
      wrong: fields.filter((f) => !f.match).map(({ match: _m, ...rest }) => rest),
    });
  }
  const perField: Record<string, Rate> = {};
  for (const f of all) {
    const g = (perField[groupPath(f.path)] ??= { matched: 0, total: 0, rate: 0 });
    g.total++;
    if (f.match) g.matched++;
  }
  for (const g of Object.values(perField)) g.rate = pct(g.matched, g.total);
  const sorted = Object.fromEntries(Object.entries(perField).sort(([a], [b]) => a.localeCompare(b)));
  const wrong = all.filter((f) => !f.match);
  const flagged = wrong.filter((f) => f.flagged).length;
  const matched = all.length - wrong.length;
  return {
    generatedAt: (opts.now ?? (() => new Date()))().toISOString(),
    model: opts.model,
    threshold: opts.threshold ?? 0.8,
    inputs,
    overall: { matched, total: all.length, rate: pct(matched, all.length) },
    perField: sorted,
    flaggedWrong: { flagged, wrong: wrong.length, rate: pct(flagged, wrong.length) },
  };
}

export function renderMarkdown(r: EvalResult): string {
  const lines = [
    '# Extraction accuracy',
    '',
    `Generated by \`eval/run-eval.ts\` from \`latest.json\`. Do not edit by hand.`,
    '',
    `- Model: ${r.model}`,
    `- Generated: ${r.generatedAt}`,
    `- Confidence threshold: ${r.threshold}`,
    `- Overall exact-match rate: ${r.overall.rate}% (${r.overall.matched} of ${r.overall.total} fields)`,
    `- Wrong fields flagged needs_confirmation: ${r.flaggedWrong.rate}% (${r.flaggedWrong.flagged} of ${r.flaggedWrong.wrong})`,
    '',
    '## Per input',
    '',
    '| Input | sha256 | Result | Kind | Matched | Rate | Flagged fields |',
    '|---|---|---|---|---|---|---|',
    ...r.inputs.map(
      (i) =>
        `| ${i.file} | \`${i.sha256}\` | ${i.ok ? 'ok, schema-valid' : `failed: ${i.reason}`} | ${i.kind ?? '-'} | ${i.matched} / ${i.total} | ${i.rate}% | ${i.needsConfirmation} |`,
    ),
    '',
    '## Per field',
    '',
    '| Field | Matched | Rate |',
    '|---|---|---|',
    ...Object.entries(r.perField).map(([p, g]) => `| \`${p}\` | ${g.matched} / ${g.total} | ${g.rate}% |`),
    '',
    '## Wrong fields',
    '',
    '| Input | Field | Expected | Read | Confidence | Flagged |',
    '|---|---|---|---|---|---|',
    ...r.inputs.flatMap((i) =>
      i.wrong.map(
        (w) =>
          `| ${i.file} | \`${w.path}\` | ${cell(w.expected)} | ${cell(w.actual)} | ${w.confidence ?? '-'} | ${w.flagged ? 'yes' : 'no'} |`,
      ),
    ),
    '',
  ];
  return lines.join('\n');
}

const cell = (v: unknown) => (v === undefined ? '(missing)' : JSON.stringify(v).replace(/\|/g, '\\|'));

export function writeResults(dir: string, r: EvalResult): void {
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'latest.json'), `${JSON.stringify(r, null, 2)}\n`);
  writeFileSync(join(dir, 'RESULTS.md'), renderMarkdown(r));
}

export function loadAcceptanceInputs(): EvalInput[] {
  return ACCEPTANCE_INPUTS.map((a) => ({
    ...a,
    bytes: new Uint8Array(readFileSync(join(SPECIMENS, a.file))),
    truth: JSON.parse(readFileSync(join(SPECIMENS, `${a.specimenId}.fields.json`), 'utf8')),
  }));
}

/** The eval over the acceptance inputs with the real extractor, in the given mode. */
export async function evalAcceptance(mode: 'live' | 'fixture', log: (s: string) => void = () => {}): Promise<EvalResult> {
  const env = readConfig();
  const config = mode === 'fixture' ? { ...env, mode: 'fixture' as const } : env;
  let model = config.model;
  return runEval({
    inputs: loadAcceptanceInputs(),
    model: mode === 'fixture' ? 'from fixtures' : model,
    extract: async (i) => {
      const t0 = Date.now();
      const r = await extractNotice({ bytes: i.bytes }, { config });
      if (r.ok) model = r.meta.model;
      log(`${i.file}: ${r.ok ? `ok ${r.meta.kind}` : `failed ${r.reason}${r.detail ? ` (${r.detail})` : ''}`} in ${Date.now() - t0} ms`);
      return r;
    },
  }).then((r) => ({ ...r, model }));
}

if ((import.meta as { main?: boolean }).main) {
  const mode = process.argv.includes('fixture') ? 'fixture' : 'live';
  const r = await evalAcceptance(mode, (s) => process.stdout.write(`${s}\n`));
  // The live run, or a replay with --write (eval:results), writes the committed results; a plain replay goes to a temp dir.
  const out = mode === 'live' || process.argv.includes('--write') ? RESULTS_DIR : mkdtempSync(join(tmpdir(), 'notice-eval-fixture-'));
  writeResults(out, r);
  process.stdout.write(`wrote ${out}\n`);
  process.stdout.write(`overall ${r.overall.rate}% (${r.overall.matched}/${r.overall.total}), flagged wrong ${r.flaggedWrong.rate}%\n`);
}
